// 클립보드 기록: 복사한 글을 기억해 두고 Baro에서 다시 찾아 붙여넣기
// - 0.5초마다 클립보드 변경 번호(changeCount)만 확인 → 바뀌었을 때만 글을 읽음 (프로세스 실행 없음)
// - 저장 안 함: 비밀번호 관리자·Baro 비밀번호 복사처럼 "숨김/임시" 표시가 붙은 것, 키·토큰처럼 보이는 글
// - 최근 200개만, clipboard.json(나만 읽기 권한 600)에 저장
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Mutex, OnceLock};

#[derive(Serialize, Deserialize, Clone, PartialEq, Debug)]
pub struct Clip { pub text: String, pub at: i64, pub app: String }

const MAX: usize = 200;
const MAX_LEN: usize = 100_000; // 이보다 긴 글(큰 로그 등)은 저장 안 함

static LIST: Mutex<Vec<Clip>> = Mutex::new(Vec::new());
static FILE: OnceLock<PathBuf> = OnceLock::new();
pub static ENABLED: AtomicBool = AtomicBool::new(true);

// 키·토큰·비밀번호처럼 보이는 글
pub fn looks_secret(s: &str) -> bool {
    let t = s.trim();
    if t.contains("PRIVATE KEY-----") { return true; }
    if t.chars().any(char::is_whitespace) { return false; }
    let prefixes = ["sk-", "ghp_", "gho_", "ghs_", "github_pat_", "xoxb-", "xoxp-", "AKIA", "AIza", "glpat-"];
    if t.len() >= 20 && prefixes.iter().any(|p| t.starts_with(p)) { return true; }
    // 공백 없는 16~100자, 주소·경로가 아니고, -·_로 나눈 한 덩어리가 무작위 글자처럼 보이면 (Bandit 비밀번호 같은 것)
    let n = t.chars().count();
    (16..=100).contains(&n)
        && t.chars().all(|c| c.is_ascii_alphanumeric() || "+=_-".contains(c))
        && t.split(['-', '_']).any(random_like)
}

// 16자 이상에 대문자·소문자·숫자가 모두 있고, 글자 종류(대·소·숫자)가 자주 바뀜
// 무작위 글자는 약 60%의 자리에서 바뀌고, CanvasRenderingContext2D 같은 이름·날짜·파일명은 훨씬 적음
fn random_like(s: &str) -> bool {
    let kind = |c: char| if c.is_ascii_uppercase() { 0 } else if c.is_ascii_lowercase() { 1 } else if c.is_ascii_digit() { 2 } else { 3 };
    let k: Vec<u8> = s.chars().map(kind).collect();
    let n = k.len();
    n >= 16 && [0, 1, 2].iter().all(|x| k.contains(x)) && k.windows(2).filter(|w| w[0] != w[1]).count() * 3 >= n
}

// 맨 앞에 넣기. 같은 글이 있으면 그 자리에서 빼고 맨 앞으로
pub fn push(list: &mut Vec<Clip>, text: &str, app: &str, at: i64) -> bool {
    if text.trim().is_empty() || text.len() > MAX_LEN || looks_secret(text) { return false; }
    if list.first().is_some_and(|c| c.text == text) { return false; }
    list.retain(|c| c.text != text);
    list.insert(0, Clip { text: text.to_string(), at, app: app.to_string() });
    list.truncate(MAX);
    true
}

fn save(list: &[Clip]) {
    let Some(f) = FILE.get() else { return };
    let tmp = f.with_extension("json.tmp");
    let Ok(b) = serde_json::to_vec(list) else { return };
    if std::fs::write(&tmp, b).is_err() { return; }
    #[cfg(unix)]
    { use std::os::unix::fs::PermissionsExt; let _ = std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(0o600)); }
    let _ = std::fs::rename(&tmp, f);
}

fn now_ms() -> i64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_millis() as i64).unwrap_or(0)
}

pub fn list() -> Vec<Clip> { LIST.lock().unwrap().clone() }

pub fn remove(at: i64, text: &str) {
    let mut l = LIST.lock().unwrap();
    l.retain(|c| !(c.at == at && c.text == text));
    save(&l);
}

pub fn clear() {
    let mut l = LIST.lock().unwrap();
    l.clear();
    save(&l);
}

// 저장된 기록을 읽고 감시 시작
pub fn start(file: &Path, enabled: bool) {
    let _ = FILE.set(file.to_path_buf());
    ENABLED.store(enabled, Ordering::Relaxed);
    if let Ok(b) = std::fs::read(file) {
        if let Ok(v) = serde_json::from_slice::<Vec<Clip>>(&b) { *LIST.lock().unwrap() = v; }
    }
    #[cfg(target_os = "macos")]
    std::thread::spawn(mac::watch);
}

// 비밀번호 복사: 다른 클립보드 앱도 기록하지 않도록 "숨김" 표시를 붙여 복사
pub fn copy_secret(text: &str) -> Result<(), String> {
    #[cfg(target_os = "macos")]
    return mac::copy_secret(text);
    #[cfg(not(target_os = "macos"))]
    { let _ = text; Err("macOS에서만 지원해요".into()) }
}

#[cfg(target_os = "macos")]
mod mac {
    use super::*;
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString, NSWorkspace};
    use objc2_foundation::NSString;

    // nspasteboard.org 약속: 비밀번호 관리자 등이 붙이는 표시
    const SKIP: &[&str] = &["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

    pub fn watch() {
        let pb = NSPasteboard::generalPasteboard();
        let mut last = pb.changeCount();
        loop {
            std::thread::sleep(std::time::Duration::from_millis(500));
            let n = pb.changeCount();
            if n == last { continue; }
            last = n;
            if !ENABLED.load(Ordering::Relaxed) { continue; }
            let types: Vec<String> = pb.types().map(|t| t.iter().map(|s| s.to_string()).collect()).unwrap_or_default();
            if types.iter().any(|t| SKIP.contains(&t.as_str())) { continue; }
            let Some(text) = pb.stringForType(unsafe { NSPasteboardTypeString }) else { continue };
            let app = NSWorkspace::sharedWorkspace().frontmostApplication()
                .and_then(|a| a.localizedName()).map(|s| s.to_string()).unwrap_or_default();
            let mut l = LIST.lock().unwrap();
            if push(&mut l, &text.to_string(), &app, now_ms()) { save(&l); }
        }
    }

    pub fn copy_secret(text: &str) -> Result<(), String> {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        let ok = pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
            && pb.setString_forType(&NSString::from_str(""), &NSString::from_str(SKIP[0]));
        if ok { Ok(()) } else { Err("클립보드에 복사하지 못했어요".into()) }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn secrets_are_skipped() {
        assert!(looks_secret("sk-ant-api03-abcdefghijklmnopqrstuvwxyz"));
        assert!(looks_secret("ghp_ABCDEFGHIJKLMNOPQRSTUVWXYZabcd1234"));
        assert!(looks_secret("-----BEGIN OPENSSH PRIVATE KEY-----\nabc"));
        assert!(looks_secret("Xk9mP2qR7sT4vW1yZ3aB5cD8eF0gH6jL")); // 32자 섞인 토큰
        assert!(!looks_secret("ls -la /etc"));
        assert!(!looks_secret("https://github.com/hmc1206/baro"));
        assert!(!looks_secret("6d4023f8a1b2c3d4e5f60718293a4b5c6d7e8f90")); // git 커밋 해시 (대문자 없음)
        assert!(!looks_secret("안녕하세요"));
        // 이름·날짜·파일명은 비밀번호가 아님
        assert!(!looks_secret("2026-11-15-Baro-"));
        assert!(!looks_secret("CanvasRenderingContext2D"));
        assert!(!looks_secret("KakaoTalk_20231015_123456789"));
        assert!(!looks_secret("ESP32-RS485-Gateway"));
        assert!(looks_secret("aB3dE5gH7jK9mN1pQ3"));
    }

    #[test]
    fn push_dedupes_and_limits() {
        let mut l = vec![];
        assert!(push(&mut l, "a", "x", 1));
        assert!(push(&mut l, "b", "x", 2));
        assert!(!push(&mut l, "b", "x", 3)); // 맨 앞과 같으면 그대로
        assert!(push(&mut l, "a", "y", 4)); // 예전 것은 맨 앞으로
        assert_eq!(l.iter().map(|c| c.text.as_str()).collect::<Vec<_>>(), ["a", "b"]);
        assert!(!push(&mut l, "   ", "x", 5));
        for i in 0..300 { push(&mut l, &format!("t{i}"), "x", i); }
        assert_eq!(l.len(), MAX);
    }
}
